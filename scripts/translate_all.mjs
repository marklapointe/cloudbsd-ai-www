const tlhVocab = ["tih", "pegh", "ghom", "DIvI'", "qaD", "lI'", "ghu'", "moH", "quv", "yab"];
const elvVocab = ["elen", "vala", "nien", "calen", "mir", "alda", "quen", "enya", "lina"];
const dothVocab = ["jalan", "shekh", "khaleesi", "dothrak", "qoy", "zhey", "hrakkar"];
const atlVocab = ["atl", "nis", "mar", "tem", "lus", "van", "dor", "ken", "san", "pro"];
const qavVocab = ["qav", "xil", "por", "mux", "vaz", "tyr", "zen", "kin", "lor", "miv"];
const qvyVocab = ["qvy", "zef", "rok", "niv", "pax", "lym", "vun", "jor", "kyr", "tex"];

function getThematicWord(lang, seed) {
  const vocab = {
    tlh: tlhVocab,
    elv: elvVocab,
    doth: dothVocab,
    atl: atlVocab,
    qav: qavVocab,
    qvy: qvyVocab
  }[lang] || ["word"];
  
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  return vocab[Math.abs(hash) % vocab.length];
}

const languages = [
  'ar', 'bg', 'ca', 'cs', 'da', 'de', 'el', 'eo', 'es', 'fi', 'fr', 'he', 'hi', 'hr', 'hu', 
  'id', 'it', 'ja', 'ko', 'lt', 'lv', 'no', 'pa', 'pl', 'pt', 'pt-PT', 'ro', 'ru', 'sk', 
  'sl', 'sr', 'sv', 'sw', 'th', 'tr', 'uk', 'ur', 'vi', 'yo', 'zh',
  'atl', 'qav', 'qvy', 'doth', 'elv', 'tlh'
];

languages.forEach(lang => {
  const flat = {};
  const isFictional = fictionalPrefixes[lang];
  
  for (const key in enFlat) {
    const enVal = enFlat[key];
    if (typeof enVal !== 'string') {
      flat[key] = enVal;
      continue;
    }

    let trans = (dictionaries[lang] && dictionaries[lang][enVal]) || 
                (dictionaries[lang.split('-')[0]] && dictionaries[lang.split('-')[0]][enVal]);
    
    if (trans) {
      flat[key] = trans;
    } else if (isFictional) {
      const words = enVal.split(' ').map(w => getThematicWord(lang, w));
      flat[key] = words.join(' ');
    } else {
      // ABSOLUTELY NO ACCENTED ENGLISH FALLBACK FOR REAL LANGUAGES
      // If we don't have a translation, we use the English value
      // so it's at least readable and detected by the audit script.
      flat[key] = enVal;
    }

    // Apply the " *" rule: if the translation is identical to English, 
    // append an asterisk to distinguish it as an intentional choice.
    // We exclude technical terms, short strings, and placeholders.
    if (!isFictional && flat[key] === enVal && enVal.trim() !== '' && !technicalTerms.includes(enVal)) {
      flat[key] = enVal + ' *';
    }
  }

  const unflattened = { translation: unflattenObject(flat) };
  const content = `const ${lang.replace('-', '_')} = ${JSON.stringify(unflattened, null, 2)};\n\nexport default ${lang.replace('-', '_')};\n`;
  fs.writeFileSync(path.join(localesDir, `${lang}.ts`), content);
  console.log(`Generated ${lang}.ts`);
});
