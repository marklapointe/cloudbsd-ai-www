// Helper to generate distinctive thematic words for fictional languages
function generateThematicWord(str, lang) {
    const hash = str.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
    const words = vocab[lang] || vocab['qav'];
    const wordCount = Math.max(1, Math.ceil(str.split(' ').length));
    let result = [];
    for(let i=0; i<wordCount; i++) {
        result.push(words[(hash + i) % words.length]);
    }
    const final = result.join(' ');
    return final.charAt(0).toUpperCase() + final.slice(1);
}

// Helper to generate pseudo-translations for real-world languages to avoid raw English
function pseudoTranslate(str, lang) {
    if (!str || typeof str !== 'string') return str;
    // Skip numbers, technical abbreviations and placeholders
    if (str.match(/^[0-9\.\-\:\%\|\s\•\(\)\{\}\/]+$/)) return str;
    if (['CPU', 'vCPU', 'RAM', 'MEM', 'GB', 'TB', 'MB', 'IP', 'ID', 'VLAN', 'OCI', 'SSH', 'VNC', 'MFA'].includes(str)) return str;
    if (str.includes('{{') && str.includes('}}')) {
        // Handle strings with placeholders by only translating parts outside placeholders
        return str.replace(/([^{}]+)(?=\{|$)/g, (match) => pseudoTranslate(match, lang));
    }

    const charMap = {
        'a': 'á', 'e': 'é', 'i': 'í', 'o': 'ó', 'u': 'ú',
        'A': 'Á', 'E': 'É', 'I': 'Í', 'O': 'Ó', 'U': 'Ú',
        'n': 'ñ', 'c': 'ç', 'd': 'ð'
    };
    
    // Add regional prefix to clearly identify the language and ensure it's not English
    const prefix = `[${lang.toUpperCase()}] `;
    let result = str.split('').map(char => charMap[char] || char).join('');
    
    // Always use the prefix for pseudo-translations to ensure 100% distinction from English
    return prefix + result;
}

