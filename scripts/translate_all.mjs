const localesDir = path.join(process.cwd(), 'src/locales');
const localeFiles = fs.readdirSync(localesDir).filter(f => f.endsWith('.ts') && f !== 'en.ts' && f !== 'index.ts');

for (const file of localeFiles) {
  const lang = file.split('.')[0];
  const dict = dictionaries[lang] || dictionaries[lang.split('-')[0]] || {};
  
  const finalFlat = {};
  for (const key in enFlat) {
    const enVal = enFlat[key];
    if (dict[enVal]) {
      finalFlat[key] = dict[enVal];
    } else {
      const isFictional = ['atl', 'doth', 'elv', 'qav', 'qvy', 'tlh'].includes(lang);
      if (isFictional) {
          finalFlat[key] = generateThematicWord(enVal, lang);
      } else {
          finalFlat[key] = pseudoTranslate(enVal, lang);
      }
    }
  }
  
  const finalObj = { translation: unflatten(finalFlat) };
  const filePath = path.join(localesDir, file);
  const content = `const ${lang.replace('-', '_')} = ${JSON.stringify(finalObj, null, 2)};\n\nexport default ${lang.replace('-', '_')};\n`;
  fs.writeFileSync(filePath, content);
  console.log(`Updated ${file}`);
}
